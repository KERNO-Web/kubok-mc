# v24: все 20 фото организаторов -> assets/orgs/<h|p>-NN.webp (900px), список с пометкой вырезка/фото
import subprocess, os, json
A='rap_photo_materials_all (1)/01_Обработанные/'
B='rap_photos_batch_2_all/02_Обработанные/'
H=[('крик_сквозь_грозовую_тьму',0),('ночная_уличная_команда_под_фонарём',0),('подпольный_свет_в_заброшенном_гараже',0),('портрет_мужчины_в_кепке_brooklyn',1),
   ('мужчина_в_чёрной_футболке_с_принтом_1977',1),('танцующий_мужчина_в_голубой_футболке',1),('портрет_мужчины_в_чёрном_свитшоте',1),('мрачный_рэп_в_подземном_переходе',0)]
P=[('винтажный_клубный_кадр_с_сигарой',0),('игрок_у_бильярдного_стола_с_напитком',0),('мужчина_с_шашлыком_и_вином',1),('уверенные_взгляды_в_синем_клубном_свете',0),
   ('изолированный_streetwear_портрет_с_цепью_из_курицы',1),('старинное_барное_торжество_с_пивом',0),('дуэт_на_фоне_studio_21',0),('мужчина_в_уличном_стиле_вид_со_спины',1)]
os.makedirs('.work/orgtmp', exist_ok=True)
out={}
for key, base, lst in (('h',A,H),('p',B,P)):
    out[key]=[]
    for i,(name,cut) in enumerate(lst,1):
        src=base+name+'.png'; tmp=f'.work/orgtmp/{key}{i}.png'; dst=f'assets/orgs/{key}-{i:02d}.webp'
        subprocess.run(['sips','-Z','900',src,'--out',tmp],check=True,capture_output=True)
        subprocess.run(['cwebp','-quiet','-q','82','-alpha_q','100',tmp,'-o',dst],check=True)
        out[key].append([f'{key}-{i:02d}',cut])
print(json.dumps(out))
